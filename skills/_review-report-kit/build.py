#!/usr/bin/env python3
"""Assemble the review report templates from the shared core.

Layout: core/base.css + core/report.js are shared; skills/<name>/ holds
config.js (constants the core reads), theme.css (that skill's colours) and
body.html (markup with <!--STYLE--> and <!--SCRIPT--> markers). The output is
each skill's references/report-template.html, one self-contained file.

  python3 build.py            write every skill's template
  python3 build.py --check    exit 1 and list the skills whose shipped file differs
  python3 build.py --out DIR  write into DIR/<name>.html instead of the skills
"""
import sys
import pathlib

KIT = pathlib.Path(__file__).resolve().parent
SKILLS_ROOT = KIT.parent
BANNER = ("<!-- GENERATED by skills/_review-report-kit/build.py from core/ and "
          "skills/{name}/ - edit those and rebuild; do not edit this file. -->\n")


def render(name):
    core_css = (KIT / "core" / "base.css").read_text()
    core_js = (KIT / "core" / "report.js").read_text()
    skill = KIT / "skills" / name
    body = (skill / "body.html").read_text()
    theme = (skill / "theme.css").read_text()
    config = (skill / "config.js").read_text()
    for marker in ("<!--STYLE-->", "<!--SCRIPT-->"):
        if body.count(marker) != 1:
            raise SystemExit(f"{name}/body.html must contain exactly one {marker}")
    html = body.replace("<!--STYLE-->", "<style>\n" + core_css + theme + "</style>")
    html = html.replace("<!--SCRIPT-->", "<script>\n(function () {\n" + config + core_js + "})();\n</script>")
    return BANNER.format(name=name) + html


def shipped(name):
    return SKILLS_ROOT / name / "references" / "report-template.html"


def main(argv):
    names = sorted(p.name for p in (KIT / "skills").iterdir() if p.is_dir())
    if "--out" in argv:
        out_dir = pathlib.Path(argv[argv.index("--out") + 1])
        out_dir.mkdir(parents=True, exist_ok=True)
        for name in names:
            (out_dir / f"{name}.html").write_text(render(name))
            print("wrote", out_dir / f"{name}.html")
        return 0
    if "--check" in argv:
        stale = [n for n in names if not shipped(n).exists() or shipped(n).read_text() != render(n)]
        if stale:
            print("stale:", ", ".join(stale))
            return 1
        print("all templates up to date:", ", ".join(names))
        return 0
    for name in names:
        shipped(name).write_text(render(name))
        print("wrote", shipped(name))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
