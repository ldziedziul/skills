// The shipped templates are generated: a hand edit or an unbuilt change
// fails here. Run from a scratch dir that has jsdom installed (the other
// tests need it): node --test ~/.claude/skills/_review-report-kit/tests/
const { test } = require("node:test");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const { spawnSync } = require("node:child_process");

const KIT = path.resolve(__dirname, "..");

test("every skill body carries exactly one STYLE and one SCRIPT marker", () => {
  const skills = fs.readdirSync(path.join(KIT, "skills"));
  assert.ok(skills.length >= 1);
  for (const s of skills) {
    const body = fs.readFileSync(path.join(KIT, "skills", s, "body.html"), "utf8");
    assert.equal((body.match(/<!--STYLE-->/g) || []).length, 1, `${s}: one STYLE marker`);
    assert.equal((body.match(/<!--SCRIPT-->/g) || []).length, 1, `${s}: one SCRIPT marker`);
  }
});

test("shipped templates match the build output", () => {
  const r = spawnSync("python3", [path.join(KIT, "build.py"), "--check"], { encoding: "utf8" });
  assert.equal(r.status, 0, `build --check failed:\n${r.stdout}\n${r.stderr}`);
});

test("generated files start with the GENERATED banner", () => {
  const skills = fs.readdirSync(path.join(KIT, "skills"));
  for (const s of skills) {
    const shipped = path.join(KIT, "..", s, "references", "report-template.html");
    const first = fs.readFileSync(shipped, "utf8").split("\n")[0];
    assert.match(first, /^<!-- GENERATED by skills\/_review-report-kit\/build\.py/, `${s}: banner`);
  }
});

test("report.js reads its wording and pill vocabulary from CONFIG, not literals", () => {
  const js = fs.readFileSync(path.join(KIT, "core", "report.js"), "utf8");
  for (const literal of ['"No comments yet"', '"Copy new comments"', '"Jump to my comment"', '["topost", "recheck", "stale"]', '"Draft comment"', '".st.act"', 'label: "Agree - post as drafted"']) {
    assert.ok(!js.includes(literal), `core/report.js still hard-codes ${literal}`);
  }
  for (const ref of ["CONFIG.noun", "CONFIG.nouns", "CONFIG.verb", "CONFIG.actionSt", "CONFIG.droppedSt", "CONFIG.groups", "CONFIG.labelSources", "CONFIG.decisions", "CONFIG.actionPill", "CONFIG.exportIntro", "CONFIG.draftLabel", "CONFIG.draftEditedSuffix", "CONFIG.noteLabel", "CONFIG.notePlaceholder", "CONFIG.draftBeforeSuggest"]) {
    assert.ok(js.includes(ref), `core/report.js does not read ${ref}`);
  }
});
